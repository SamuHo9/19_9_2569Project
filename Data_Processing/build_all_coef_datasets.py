"""Create the three no-PLS coefficient cohorts used by the leakage-free runner.

Only the original train/test coefficient exports are copied.  The balanced
folders are intentionally excluded because they were generated by the PLS-DA
interpolation augmenter.
"""
import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd


COHORTS = {
    'All_coef': 'ALL',
    'All_coef_Ds004469': 'Ds004469',
    'All_coef_Ds005602': 'Ds005602',
}
SIDES = ('left', 'right')
META = ['Subject', 'Group', 'Class', 'BinaryClass', 'DataType']


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def main():
    parser = argparse.ArgumentParser()
    default_root = Path(__file__).resolve().parents[1]
    parser.add_argument('--project_root', type=Path, default=default_root)
    args = parser.parse_args()

    project = args.project_root.resolve()
    output = project / 'Model' / 'Output_Dataset'
    rows = []
    for cohort, source in COHORTS.items():
        family = project / 'Model' / cohort
        for side in SIDES:
            stem = f'{source}_{side.capitalize()}'
            side_dir = family / side
            side_dir.mkdir(parents=True, exist_ok=True)
            for split in ('train', 'test'):
                source_csv = output / f'{stem}_{split}_coef_features.csv'
                source_manifest = Path(str(source_csv) + '.json')
                if not source_csv.is_file() or not source_manifest.is_file():
                    raise FileNotFoundError(f'Missing canonical coefficient export: {source_csv}')
                frame = pd.read_csv(source_csv)
                features = [c for c in frame.columns if c.startswith('Coef_')]
                if len(features) != 507:
                    raise ValueError(f'{source_csv} has {len(features)} coefficient values, expected 507')
                if not frame['DataType'].fillna('Original').str.lower().isin(['original', 'real']).all():
                    raise ValueError(f'Non-original rows found in {source_csv}')
                if frame['Subject'].duplicated().any():
                    raise ValueError(f'Duplicate subjects found in {source_csv}')
                target_name = f'{cohort}_{side.capitalize()}_{split}_coef_features.csv'
                target_csv = side_dir / target_name
                frame.to_csv(target_csv, index=False, float_format='%.8f')
                source_payload = json.loads(source_manifest.read_text(encoding='utf-8'))
                payload = {
                    'csv_sha256': sha256(target_csv),
                    'feature_contract': source_payload.get('feature_contract', {}),
                    'dataset': cohort,
                    'source_dataset': source,
                    'side': side,
                    'split': split,
                    'protocol': 'original-coef-no-pls-v1',
                    'rows': len(frame),
                    'schema': list(frame.columns),
                    'pls_da_applied_to_model_input': False,
                    'synthetic_rows': int((frame['DataType'].str.lower() == 'augmented').sum()),
                }
                Path(str(target_csv) + '.json').write_text(json.dumps(payload, indent=2), encoding='utf-8')
                rows.append({
                    'Dataset': cohort,
                    'SourceDataset': source,
                    'Side': side,
                    'Split': split,
                    'Rows': len(frame),
                    'Class0': int((frame['BinaryClass'] == 0).sum()),
                    'Class1': int((frame['BinaryClass'] == 1).sum()),
                    'Features': len(features),
                    'PLSDA': False,
                    'File': str(target_csv),
                })
    manifest = project / 'Model' / 'All_coef_manifest.csv'
    pd.DataFrame(rows).to_csv(manifest, index=False)
    contract = {
        'version': 'original-coef-no-pls-v1',
        'cohorts': list(COHORTS),
        'sides': list(SIDES),
        'splits': ['train', 'test'],
        'features': 'Coef_1..Coef_507',
        'pls_da_applied_to_model_input': False,
        'balanced_split_excluded': True,
        'test_policy': 'original-only; never used for preprocessing, tuning, threshold selection, or early stopping',
    }
    (project / 'Model' / 'All_coef_contract.json').write_text(json.dumps(contract, indent=2), encoding='utf-8')
    print(f'Created {len(rows)} no-PLS files under Model/All_coef*')
    print(f'Manifest: {manifest}')


if __name__ == '__main__':
    main()
